"""CQI reference rules: bands, slabs, severity, action codes, the rule table.

This is the fixed vocabulary the reasoning / learning layers share:

* **Bands** for an average (0..1): Very Low <50%, Low 50-59%, Medium 60-69%,
  High >=70%.
* **Slab** (0-3) of a scaled attainment and the **severity** of a miss.
* **Course type** (Theory / Practical): the same reason gets a different
  corrective action in a lab course.
* **Action codes** (A01...): a closed list, so "which action was taken" is
  data a model can learn from instead of free text.
* **Context** features that are *not* part of the attainment formula (course
  type, Bloom level, mapping strength, class size, previous attainment). A
  classifier trained only on Internal/External/Indirect just relearns the
  rules; these are what let it learn something new.
* ``build_rule_table`` — every band x band x band x course-type combination
  (128 rows) with slab, reason, severity and action, generated by running the
  *real* pipeline and expert tree, so the table can never disagree with the app.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from io import StringIO

from .features import BLOOM_INDEX

COURSE_TYPES: tuple[str, ...] = ("Theory", "Practical")

BAND_NAMES: tuple[str, ...] = ("Very Low", "Low", "Medium", "High")
BAND_CUTS: tuple[float, ...] = (0.50, 0.60, 0.70)          # lower bounds of Low / Medium / High
BAND_MIDPOINTS: tuple[float, ...] = (0.40, 0.55, 0.65, 0.80)


def band(value: float) -> int:
    """Band index 0..3 of an average on the 0..1 scale."""
    return sum(1 for cut in BAND_CUTS if value >= cut - 1e-9)


def band_name(value: float) -> str:
    return BAND_NAMES[band(value)]


def slab(scaled: float) -> int:
    """Attainment slab 0..3 of a scaled (0..3) attainment."""
    if scaled >= 2.5:
        return 3
    if scaled >= 2.0:
        return 2
    if scaled >= 1.0:
        return 1
    return 0


SEVERITY_BY_SLAB: dict[int, str] = {
    0: "Major: escalate to the programme assessment committee and review the syllabus",
    1: "Moderate: remedial plan for the next semester",
    2: "Minor: reinforce so it does not slip",
    3: "Sustain: consider raising the target",
}


def severity(scaled: float) -> str:
    return SEVERITY_BY_SLAB[slab(scaled)]


# ---------------------------------------------------------------------------
# Context features
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class Context:
    course_type: str = ""            # "Theory" | "Practical" | ""
    bloom_level: str = ""            # remember..create | ""
    map_strength: float | None = None   # mean non-zero CO-PO strength of the CO's row
    class_size: int | None = None
    prev_attained: float | None = None  # same CO, previous offering (scaled 0..3)


CONTEXT_FEATURE_NAMES = ["is_practical", "bloom", "map_strength", "class_size", "prev_attained"]
UNKNOWN = -1.0


def context_features(ctx: Context | None) -> list[float]:
    """Numeric context vector; unknown values are -1 (constant for seed rows)."""
    if ctx is None:
        return [0.0, UNKNOWN, UNKNOWN, UNKNOWN, UNKNOWN]
    return [
        1.0 if ctx.course_type.strip().lower() == "practical" else 0.0,
        float(BLOOM_INDEX[ctx.bloom_level]) if ctx.bloom_level in BLOOM_INDEX else UNKNOWN,
        float(ctx.map_strength) if ctx.map_strength is not None else UNKNOWN,
        float(ctx.class_size) if ctx.class_size is not None else UNKNOWN,
        float(ctx.prev_attained) if ctx.prev_attained is not None else UNKNOWN,
    ]


