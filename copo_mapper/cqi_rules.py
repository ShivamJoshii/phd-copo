RULE_TABLE_FIELDS = [
    "course_type", "internal_band", "end_sem_band", "indirect_band",
    "final_scaled", "slab", "achieved", "reason_code", "reason", "severity",
    "action_codes", "action_taken",
]


def build_rule_table(
    target: float = 2.0,
    ma_weight: float = 0.4,
    direct_weight: float = 0.8,
) -> list[dict[str, str]]:
    """All internal x end-sem x indirect band x course-type combinations.

    Each row is computed by the production pipeline at the band midpoints, so
    the table is a faithful printout of what the app would say.
    """
    from .action_plan import REASON_TAXONOMY, suggest_reason_co  # noqa: PLC0415
    from .attainment import COAttainmentInput, WeightConfig, compute_co_attainment  # noqa: PLC0415
    from .diagnostics import diagnose_co  # noqa: PLC0415

    config = WeightConfig(ma_weight, 1 - ma_weight, direct_weight, 1 - direct_weight, target, target)
    rows: list[dict[str, str]] = []
    for course_type in COURSE_TYPES:
        for i_band, ma in enumerate(BAND_MIDPOINTS):
            for e_band, ea in enumerate(BAND_MIDPOINTS):
                for s_band, ind in enumerate(BAND_MIDPOINTS):
                    (result,) = compute_co_attainment([COAttainmentInput("CO", ma, ea, ind)], config)
                    exp = diagnose_co(result, config)
                    suggestion = suggest_reason_co(exp)
                    row = {
                        "course_type": course_type,
                        "internal_band": BAND_NAMES[i_band],
                        "end_sem_band": BAND_NAMES[e_band],
                        "indirect_band": BAND_NAMES[s_band],
                        "final_scaled": f"{result.scaled_attainment:.2f}",
                        "slab": str(slab(result.scaled_attainment)),
                        "achieved": "Y" if exp.achieved else "N",
                        "reason_code": "",
                        "reason": "Target met",
                        "severity": severity(result.scaled_attainment) if not exp.achieved else "Sustain",
                        "action_codes": "",
                        "action_taken": "Sustain current practice.",
                    }
                    if suggestion is not None:
                        acts = actions_for(suggestion.reason_id, course_type)
                        row.update(
                            reason_code=REASON_CODES.get(suggestion.reason_id, ""),
                            reason=REASON_TAXONOMY[suggestion.reason_id].label,
                            action_codes=", ".join(code for code, _ in acts),
                            action_taken=" ".join(text for _, text in acts),
                        )
                    rows.append(row)
    return rows


def rule_table_csv(**kwargs) -> str:
    buf = StringIO()
    writer = csv.DictWriter(buf, fieldnames=RULE_TABLE_FIELDS)
    writer.writeheader()
    writer.writerows(build_rule_table(**kwargs))
    return buf.getvalue()
