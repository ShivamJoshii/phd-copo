def actions_for(reason_id: str, course_type: str = "") -> list[tuple[str, str]]:
    """[(action_code, wording for this course type)] recommended for a reason."""
    codes = REASON_ACTION_CODES.get(reason_id, ("A99",))
    return [(code, ACTION_CATALOG[code].text(course_type)) for code in codes]


def action_label(code: str) -> str:
    action = ACTION_CATALOG.get(code)
    return f"{code} {action.label}" if action else code


# ---------------------------------------------------------------------------
# The 128-combination rule table
